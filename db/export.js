#!/usr/bin/env node
// Regenerates db/schema/<name>.sql (structure) and db/seed/<name>.sql (starter
// data) from the running PostgreSQL instances listed in tenants.json.
// db/setup.js loads these files to build a fresh install.
// Usage: node db/export.js      (instances must be running: node startAll.js)

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { Client } = require('pg');

const PG_BIN = process.env.PG_BIN || '/usr/local/opt/postgresql@17/bin';
const BASE_DIR = path.join(__dirname, '..');
const SCHEMA_DIR = path.join(__dirname, 'schema');
const SEED_DIR = path.join(__dirname, 'seed');
const registry = JSON.parse(fs.readFileSync(path.join(BASE_DIR, 'tenants.json'), 'utf8'));

// Tables whose rows are tenant activity, not starter data. photos rows also
// point at files in uploads/, which isn't in the repo.
const SKIP_TABLES = ['sendemail', 'photos', 'fompages'];

// Rows kept out of the public seed (personal content), keyed by table name.
const ROW_FILTERS = {
  widgets: 'id NOT IN (1, 14)',
  // Press-release text with people's contact emails.
  plays: "COALESCE(body, '') !~* '[a-z0-9._%+-]+@[a-z0-9.-]+\\.[a-z]{2,}'",
};

const ident = (s) => '"' + s.replace(/"/g, '""') + '"';

async function exportSeed(name, inst, appSchemas) {
  // Return every value as Postgres's own text form so the INSERTs round-trip
  // exactly (timestamps, numerics, jsonb) without JS type conversion.
  const client = new Client({
    host: 'localhost',
    user: process.env.USER,
    database: inst.database,
    port: inst.port,
    types: { getTypeParser: () => (v) => v },
  });
  await client.connect();
  try {
    const { rows: tables } = await client.query(
      `SELECT schemaname, tablename FROM pg_tables
       WHERE schemaname NOT IN ('pg_catalog', 'information_schema')
         AND NOT (schemaname = ANY($1)) AND NOT (tablename = ANY($2))
       ORDER BY schemaname, tablename`,
      [appSchemas, SKIP_TABLES],
    );
    const out = [
      `-- Seed data for "${name}". Generated by db/export.js — regenerate, don't hand-edit.`,
      '-- replica mode skips triggers, so rows load exactly as exported',
      '-- (e.g. rex_path would otherwise get trg_default_settings merged in).',
      'SET session_replication_role = replica;',
      '',
    ];
    let total = 0;
    for (const { schemaname, tablename } of tables) {
      const qualified = `${ident(schemaname)}.${ident(tablename)}`;
      const where = ROW_FILTERS[tablename] ? ` WHERE ${ROW_FILTERS[tablename]}` : '';
      const { rows, fields } = await client.query(
        `SELECT * FROM ${qualified}${where} ORDER BY 1`,
      );
      if (!rows.length) continue;
      const cols = fields.map((f) => ident(f.name)).join(', ');
      out.push(`-- ${schemaname}.${tablename}: ${rows.length} rows`);
      for (const row of rows) {
        const vals = fields
          .map((f) => (row[f.name] == null ? 'NULL' : client.escapeLiteral(row[f.name])))
          .join(', ');
        out.push(`INSERT INTO ${qualified} (${cols}) VALUES (${vals});`);
      }
      // Move serial sequences past the seeded ids so new rows don't collide.
      const { rows: serials } = await client.query(
        `SELECT column_name FROM information_schema.columns
         WHERE table_schema = $1 AND table_name = $2 AND column_default LIKE 'nextval(%'`,
        [schemaname, tablename],
      );
      for (const { column_name } of serials) {
        const col = ident(column_name);
        out.push(
          `SELECT setval(pg_get_serial_sequence(${client.escapeLiteral(qualified)}, ${client.escapeLiteral(column_name)}), ` +
            `COALESCE(MAX(${col}), 1), MAX(${col}) IS NOT NULL) FROM ${qualified};`,
        );
      }
      out.push('');
      total += rows.length;
    }
    fs.writeFileSync(path.join(SEED_DIR, `${name}.sql`), out.join('\n'));
    return total;
  } finally {
    await client.end().catch(() => {});
  }
}

async function main() {
  fs.mkdirSync(SCHEMA_DIR, { recursive: true });
  fs.mkdirSync(SEED_DIR, { recursive: true });
  const allInstances = { admin: registry.admin, ...registry.tenants };

  for (const [name, inst] of Object.entries(allInstances)) {
    // Each app owns a schema of the same name and ships its own schema.sql
    // (tenants/<prefix>/<app>/schema.sql), so leave those out of the dump.
    const appSchemas = inst.apps || [];
    const excludes = appSchemas.map((s) => `-N ${s}`).join(' ');
    try {
      execSync(
        `"${PG_BIN}/pg_dump" -h localhost -p ${inst.port} -U ${process.env.USER} ` +
          `--schema-only --no-owner --no-privileges --restrict-key=fomexport ${excludes} ` +
          `-f "${path.join(SCHEMA_DIR, `${name}.sql`)}" ${inst.database}`,
        { stdio: 'pipe' },
      );
      const rows = await exportSeed(name, inst, appSchemas);
      console.log(`✔ ${name}: schema + ${rows} seed rows`);
    } catch (e) {
      const msg = e.stderr?.toString() || e.message;
      console.error(`✘ ${name} failed: ${msg.trim()}`);
      process.exitCode = 1;
    }
  }
}

main();
